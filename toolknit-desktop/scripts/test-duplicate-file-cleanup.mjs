import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { initialKeepers, selectExtras, toggleFileSelection, removalPlan, summary, filterGroups, applyRemoval, sortGroups, cleanupOutcome } from '../src/features/duplicate-file-cleanup/core.js';
import { ALL_EXTENSIONS } from '../src/features/duplicate-file-cleanup/file-types.js';
import defaultMarkup, { TOOL_MARKUP } from '../src/features/duplicate-file-cleanup/template.js';
import { LAZY_TOOL_SPECS } from '../src/features/lazy-tools.js';
const groups = [{ id: 'g1', files: [{ path: 'D:/a.txt', name: 'a.txt', size_bytes: 8, modified_at: 2 }, { path: 'D:/copy/a.bin', name: 'a.bin', size_bytes: 8, modified_at: 1 }, { path: 'D:/else/a.txt', name: 'a.txt', size_bytes: 8, modified_at: 3 }] }];
const keepers = initialKeepers(groups);
assert.equal(keepers.get('g1'), 'D:/copy/a.bin');
const selected = selectExtras(groups, keepers);
assert.equal(selected.size, 2);
assert.deepEqual(summary(groups, selected), { groups: 1, redundant: 16, selectedBytes: 16, selectedCount: 2 });
assert.deepEqual(removalPlan(groups, keepers, selected)[0].paths, ['D:/a.txt', 'D:/else/a.txt']);
assert.throws(() => removalPlan(groups, keepers, new Set(['D:/copy/a.bin'])), /invalid-keeper/);
assert.throws(() => removalPlan(groups, new Map(), selected), /invalid-keeper/);
assert.throws(() => removalPlan(groups, new Map([['g1', 'D:/missing.txt']]), selected), /invalid-keeper/);
const fiveCopies = { id: 'five', files: Array.from({ length: 5 }, (_, n) => ({ path: `D:/copy-${n}.pdf`, size_bytes: 10, modified_at: n })) };
const fiveKeepers = initialKeepers([fiveCopies]);
let choices = new Set();
assert.deepEqual(removalPlan([fiveCopies], fiveKeepers, choices), [], 'initial retention never schedules deletion');
for (let n = 0; n < 4; n++) {
  const result = toggleFileSelection(fiveCopies, fiveKeepers, choices, fiveCopies.files[n].path);
  assert.equal(result.blocked, false);
  choices = result.selected; fiveKeepers.set('five', result.keepPath);
}
assert.equal(choices.size, 4);
assert.equal(fiveKeepers.get('five'), 'D:/copy-4.pdf', 'keeper moves to a retained member when the original is selected');
const blocked = toggleFileSelection(fiveCopies, fiveKeepers, choices, 'D:/copy-4.pdf');
assert.equal(blocked.blocked, true);
assert.equal(blocked.selected, choices, 'guard leaves selection unchanged');
assert.equal(removalPlan([fiveCopies], fiveKeepers, choices)[0].paths.length, 4);
const retain = toggleFileSelection(fiveCopies, fiveKeepers, choices, 'D:/copy-1.pdf');
assert.equal(retain.selected.size, 3);
assert.equal(choices.size, 4, 'toggle does not mutate the previous selection');
assert.ok(!retain.selected.has('D:/copy-1.pdf'));
assert.throws(() => removalPlan([fiveCopies], fiveKeepers, new Set(fiveCopies.files.map(file => file.path))), /invalid-keeper/);
assert.throws(() => toggleFileSelection(fiveCopies, fiveKeepers, choices, 'D:/foreign.pdf'), /invalid-member/);
const unrelated = new Set([...choices, 'D:/other.pdf']);
assert.ok(toggleFileSelection(fiveCopies, fiveKeepers, unrelated, 'D:/copy-1.pdf').selected.has('D:/other.pdf'), 'other groups stay untouched');
assert.equal(selectExtras([fiveCopies], fiveKeepers).size, 4);
assert.equal(filterGroups(groups, 'COPY').length, 1);
assert.equal(filterGroups(groups, 'missing').length, 0);
const after = applyRemoval(groups, { items: [{ path: 'D:/a.txt', ok: true }, { path: 'D:/else/a.txt', ok: false }] });
assert.equal(after[0].files.length, 2); assert.equal(groups[0].files.length, 3);
assert.equal(summary(after).redundant, 8);
assert.equal(applyRemoval(after, { items: [{ path: 'D:/else/a.txt', ok: true }] }).length, 0);
const ids = [...TOOL_MARKUP.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(defaultMarkup, TOOL_MARKUP, 'lazy registry mounts the default template export');
assert.equal(ids.length, new Set(ids).size);
assert.ok(ids.includes(LAZY_TOOL_SPECS['duplicate-file-cleanup'].overlayId));
assert.ok(TOOL_MARKUP.indexOf('id="duplicateCleanupDialog"') > TOOL_MARKUP.indexOf('</main>'));
assert.match(TOOL_MARKUP, /id="duplicateChoose"/);
assert.match(TOOL_MARKUP, /id="duplicateAllDrives"/);
const css = await readFile('src/features/duplicate-file-cleanup/duplicate-file-cleanup.css', 'utf8');
assert.match(css, /input\[type="checkbox"\][^{]*\{[^}]*border-radius:\s*50%/s);
assert.match(css, /data-theme="dark"[^}]*input\[type="checkbox"\]/);
assert.match(css, /duplicate-members[^}]*background:\s*var\(--dup-expanded-surface\)/s);
assert.match(css, /duplicate-group\s*\{\s*border:\s*0/s);
assert.match(css, /duplicate-group\s*\+\s*\.duplicate-group[^}]*border-top:\s*1px/s);
assert.match(css, /#duplicateRemove svg[^}]*width:\s*14px/s);
const controller = await readFile('src/features/duplicate-file-cleanup/controller.js', 'utf8');
assert.doesNotMatch(controller, /if \(!busy \|\| cleaning/);
assert.match(controller, /cleanupView\.update\(value\)/);
assert.equal(cleanupOutcome({ items: [{ ok: true }] }), 'success');
assert.equal(cleanupOutcome({ items: [{ ok: true }, { ok: false }] }), 'partial');
assert.equal(cleanupOutcome({ items: [{ ok: false }] }), 'failure');
assert.equal(cleanupOutcome({ items: [], cancelled: true }), 'stopped');
assert.equal(cleanupOutcome({ items: [], uncertain: true }), 'error');
assert.match(controller, /allDrives:\s*scanMode\s*===\s*'all'/);
assert.match(controller, /q\('AllDrives'\)\.disabled\s*=\s*busy/);
assert.match(controller, /groupCopies/);
assert.match(controller, /groupSize/);
assert.match(controller, /groupRedundant/);
assert.doesNotMatch(controller, /check\.type = 'checkbox'/);
const zh = JSON.parse(await readFile('src/locales/zh.json', 'utf8'));
const en = JSON.parse(await readFile('src/locales/en.json', 'utf8'));
assert.deepEqual(Object.keys(zh.home.duplicateFileCleanup).sort(), Object.keys(en.home.duplicateFileCleanup).sort());
for (const key of [...TOOL_MARKUP.matchAll(/data-i18n(?:-placeholder|-aria-label)?="home.duplicateFileCleanup\.([^"]+)"/g)].map(match => match[1])) {
  assert.ok(zh.home.duplicateFileCleanup[key], key); assert.ok(en.home.duplicateFileCleanup[key], key);
}
const runner = await readFile('src-tauri/src/native_runtime/runner.rs', 'utf8');
for (const name of ['scan_duplicate_files', 'cancel_duplicate_file_scan', 'get_duplicate_file_progress', 'recycle_duplicate_files']) assert.ok(runner.includes(`system_runtime::duplicate_files::${name}`));
const duplicateRust = await readFile('src-tauri/src/native_runtime/duplicate_files.rs', 'utf8');
assert.match(duplicateRust, /all_drives:\s*bool/);
const nativeTypes = duplicateRust.match(/const COMMON_EXTENSIONS:[\s\S]*?=\s*&\[([\s\S]*?)\];/)[1];
assert.deepEqual([...nativeTypes.matchAll(/"([a-z0-9]+)"/g)].map(match => match[1]), ALL_EXTENSIONS, 'UI and native extension whitelist match');
assert.equal(ALL_EXTENSIONS.length, new Set(ALL_EXTENSIONS).size);
const larger = { id: 'large', files: [{ size_bytes: 100 }, { size_bytes: 100 }] };
assert.equal(sortGroups([...groups, larger])[0].id, 'large');
console.log('Duplicate cleanup: selection, keeper protection, partial results, catalog and translations passed.');
